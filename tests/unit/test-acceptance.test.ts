import { describe, it, expect } from 'vitest';
import fs from 'fs';
import { extractPDFRawData } from '../../src/lib/parsers/pdf';
import { parsePDFIntelligent } from '../../src/lib/parsers/intelligent-parser';

describe('Intelligent Parser Acceptance Tests with Real PDFs', () => {
  const p2022 = 'C:/Users/admin/Downloads/Acct_Statement_XXXXXXXX3597_2022.pdf';
  const pass2022 = '46818820';

  it('verifies 2022 real HDFC statement acceptance criteria with password', async () => {
    if (!fs.existsSync(p2022)) {
      console.warn('2022 file not found at:', p2022);
      return;
    }
    const buf2022 = fs.readFileSync(p2022);
    const pdfData = await extractPDFRawData(buf2022.buffer, pass2022);
    const result = await parsePDFIntelligent(buf2022.buffer, {
      bankHint: 'HDFC',
      preExtracted: pdfData,
    });

    console.log('--- 2022 Real PDF Parse Results ---');
    console.log('1. Total rows:', result.rows.length);
    const debits = result.rows.filter(r => r.Debit && parseFloat(r.Debit) > 0);
    const credits = result.rows.filter(r => r.Credit && parseFloat(r.Credit) > 0);
    const totalDebits = debits.reduce((acc, r) => acc + parseFloat(r.Debit), 0);
    const totalCredits = credits.reduce((acc, r) => acc + parseFloat(r.Credit), 0);

    console.log('2. Debit rows =', debits.length, ', sum of debits =', totalDebits.toFixed(2));
    console.log('3. Credit rows =', credits.length, ', sum of credits =', totalCredits.toFixed(2));

    const interestRow = result.rows.find(
      r => (/INTEREST/i.test(r.Narration) || /INTEREST/i.test(r['Ref No./Cheque No.'])) && parseFloat(r.Credit) === 145
    );
    console.log('4. Interest Row (145.00):', interestRow ? {
      date: interestRow.Date,
      debit: interestRow.Debit,
      credit: interestRow.Credit,
      balance: interestRow.Balance,
      narration: interestRow.Narration,
    } : 'NOT FOUND');

    const refRow = result.rows.find(
      r => r['Ref No./Cheque No.']?.includes('234673448595') || r.Narration?.includes('234673448595')
    );
    console.log('5. Ref 234673448595 Row:', refRow ? {
      date: refRow.Date,
      debit: refRow.Debit,
      credit: refRow.Credit,
      balance: refRow.Balance,
      reference: refRow['Ref No./Cheque No.'],
      narration: refRow.Narration,
    } : 'NOT FOUND');

    const forbidden = [
      'STATEMENT SUMMARY', 'Opening Balance', 'Dr Count', 'Cr Count', 'Closing Bal',
      'Generated On', 'Generated By', 'Requesting Branch Code', 'not require signature',
      'Contents of this statement', 'Address :', 'Registered Office', 'GSTN', 'CIN :', 'www.'
    ];

    let violations = 0;
    for (let i = 0; i < result.rows.length; i++) {
      const r = result.rows[i];
      for (const f of forbidden) {
        if (r.Narration?.toLowerCase().includes(f.toLowerCase())) {
          console.error(`Row ${i + 1} has forbidden string "${f}": ${r.Narration}`);
          violations++;
        }
      }
    }
    console.log('6. Forbidden string violations:', violations);

    const flagged = result.rows.filter(r => r.needs_review === 'true');
    console.log('7. Flagged for review (needs_review):', flagged.length, `(${((flagged.length / result.rows.length) * 100).toFixed(1)}%)`);

    expect(result.rows.length).toBe(731);
    expect(debits.length).toBe(625);
    expect(credits.length).toBe(106);
    expect(Math.abs(totalDebits - 1852984.02)).toBeLessThan(0.05);
    expect(Math.abs(totalCredits - 1874743.08)).toBeLessThan(0.05);
    expect(interestRow).toBeDefined();
    expect(parseFloat(interestRow!.Credit)).toBe(145);
    expect(parseFloat(interestRow!.Balance)).toBe(53567.32);
    expect(refRow).toBeDefined();
    expect(parseFloat(refRow!.Debit)).toBe(1);
    expect(violations).toBe(0);
    expect(flagged.length / result.rows.length).toBeLessThan(0.05);
  });
});
